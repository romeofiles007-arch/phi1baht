#!/usr/bin/env node
/**
 * ทดสอบด่านกันบทเสีย + ตัวสุ่มหมวด
 *
 *   node scripts/test-script-guard.mjs
 *
 * ที่มา (19 พ.ย. 2026): ผลิตต่อเนื่องปล่อยคลิปเสียออกมา 1 คลิป และทำสามก๊กซ้ำ 3 รอบติด
 *   1. ChatGPT ถามกลับแทนที่จะเขียนบท ("ต้องการให้ใช้บุคคลใดเป็นตัวเอกครับ?")
 *      ระบบรับคำถามนั้นเป็นบท แล้วพากย์ ทำซับ ทำภาพ 16 ใบ เรนเดอร์เป็นคลิป 34 วินาที
 *      และตั้งเวลาโพสต์ขึ้นเพจต่อเอง
 *   2. สัดส่วนหมวด 34/33/33 ทำให้คลิปแรกของทุกชุดเป็นหมวดที่ตั้ง % สูงสุดแบบตายตัว
 *      และคลิปที่ล้มไม่ถูกนับ คิวหมวดจึงไม่ขยับ — ได้หมวดเดิมซ้ำไม่รู้จบ
 */
import { scriptProblem } from '../pipeline/lib/stage2.mjs'
import { shareGenre } from '../bridge/production.js'

let fail = 0
const ok = (cond, name, extra = '') => {
  console.log(`  ${cond ? '✓' : '✗'} ${name}${extra ? ` — ${extra}` : ''}`)
  if (!cond) fail++
}

console.log('\nด่านกันบทเสีย')

// บทจริงที่หลุดออกมาเป็นคลิป
const askBack = `ข้อมูลบุคคลมีจุดที่ต้องยืนยันก่อนเขียน เพื่อไม่ให้คลิปเล่าผิดคนครับ

หันสิน (韓信 — Hán Xìn) ขุนพลผู้มีชื่อเสียงในสมัยฌ้อปาอ๋องกับหลิวปัง มีเรื่องเล่าเกี่ยวกับการลอดหว่างขา

หันเซียม (韓暹 — Hán Xiān) ผู้นำกลุ่มโจรและขุนพลปลายราชวงศ์ฮั่นตะวันออก เสียชีวิต ค.ศ. 197 ตามข้อมูลที่แนบมา

ทั้งสองเป็นคนละบุคคลกัน และเรื่องวาดงูเติมขาก็ไม่ใช่เหตุการณ์ของหันสินโดยตรง

ต้องการให้ใช้บุคคลใดเป็นตัวเอกครับ?`

// บทปกติที่จบด้วยคำถามชวนคิด — ห้ามจับผิด เพราะคลิปส่วนใหญ่จบแบบนี้
const normal = `กองทัพนับหมื่นประชิดกำแพงเมืองในเช้าวันนั้น
ขงเบ้งสั่งเปิดประตูเมืองทั้งสองบาน แล้วขึ้นไปนั่งดีดพิณบนกำแพง
สุมาอี้มองอยู่ครู่หนึ่ง แล้วสั่งถอยทัพกลับทั้งกองทัพ
ความนิ่งของคนคนเดียว หยุดกองทัพทั้งกองได้
เพราะสิ่งที่น่ากลัวที่สุด ไม่ใช่สิ่งที่เห็น แต่คือสิ่งที่เดาไม่ออก
แล้วคุณล่ะ ครั้งสุดท้ายที่เลือกจะนิ่ง คือเมื่อไหร่?`

ok(scriptProblem(askBack) !== null, 'จับคำตอบที่ ChatGPT ถามกลับแทนการเขียนบท', scriptProblem(askBack) ?? '')
ok(scriptProblem(normal) === null, 'ไม่จับผิดบทปกติที่จบด้วยคำถามชวนคิด', scriptProblem(normal) ?? '')
ok(scriptProblem('') !== null, 'จับบทว่าง')
ok(scriptProblem('   \n\n  ') !== null, 'จับบทที่มีแต่ช่องว่าง')
ok(scriptProblem(normal, { minutes: 0.2, target: 1 }) !== null, 'จับบทสั้นผิดปกติ (0.2 จากเป้า 1 นาที)')
ok(scriptProblem(normal, { minutes: 0.9, target: 1 }) === null, 'บทความยาวปกติผ่าน')
ok(scriptProblem('Which character would you like me to use?') !== null, 'จับคำถามกลับภาษาอังกฤษ')

console.log('\nตัวสุ่มหมวดตามสัดส่วน')

const share = { sanguo: 34, sage: 33, tale: 33 }
const ROUNDS = 3000

// คลิปแรกของชุด (made ว่าง) — เดิมได้หมวดที่ % สูงสุดทุกครั้ง
const first = {}
for (let i = 0; i < ROUNDS; i++) {
  const g = shareGenre(share, {}, Math.random)
  first[g] = (first[g] ?? 0) + 1
}
ok(Object.keys(first).length === 3, 'คลิปแรกของชุดกระจายครบทั้ง 3 หมวด', Object.values(first).join(' / '))
const lowest = Math.min(...Object.values(first)) / ROUNDS
ok(lowest > 0.2, 'ไม่มีหมวดไหนถูกกดต่ำผิดปกติ', `น้อยสุด ${(lowest * 100).toFixed(1)}%`)

// โควตายังต้องทำงาน: ทำหมวดหนึ่งไปแล้ว คลิปถัดไปต้องเป็นหมวดอื่น
const next = new Set()
for (let i = 0; i < 500; i++) next.add(shareGenre(share, { sanguo: 1 }, Math.random))
ok(next.size === 2 && ![...next].some((n) => n.startsWith('หมวด 1')), 'ทำหมวด 1 ไปแล้ว คลิปถัดไปสลับหมวดเสมอ', [...next].join(' / '))

// ไม่ได้ตั้งสัดส่วน → null (คละหมวดแบบเดิม)
ok(shareGenre({}, {}, Math.random) === null, 'ไม่ได้ตั้งสัดส่วน → คละหมวดแบบเดิม')

console.log(fail ? `\nตก ${fail} ข้อ` : `\nผ่าน ${11 - fail} ข้อ`)
process.exit(fail ? 1 : 0)

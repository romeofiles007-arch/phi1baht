test('จับบทที่เฉลยไม่เป็นคำพูด (ตัดจบแบบงงๆ)', () => {
  assert.equal(lacksReveal(CUT_SHORT), true, 'บทที่ล้มจริงต้องโดนจับ')
  assert.equal(lacksReveal(EXPLAINED), false, 'บทที่เฉลยเป็นคำพูดต้องผ่าน')
  // บทสั้นมาก (เศษบท/ทดสอบ) ไม่ตัดสิน — ไม่ให้ขั้นทดสอบสั้นๆ ถูกตีกลับ
  assert.equal(lacksReveal('กลางดึก... เสียงเล็บขูดดังจากใต้ถุนเรือน\nทิดมั่นสะดุ้งตื่น'), false)
  assert.equal(lacksReveal(''), false)
  // ภาษาอังกฤษใช้กฎเดียวกัน
  assert.equal(lacksReveal('A.\nB.\nC.\nD.\nE.\nThe truth was simpler: the lamp was never hers.\nF.\nG.'), false)
})

test('ถ้าโมเดลลอกป้าย "← ① เฉลย" จากฉากตัวอย่างมาด้วย ต้องไม่หลุดไปเป็นเสียงพากย์', () => {
  const out = cleanScript('ผีตัวนั้นไม่ได้มาเอาชีวิตเขา    ← ① เฉลย\nเขาทิ้งขวานไว้กลางป่า\n← ③ ข้อคิด\nลูกไม่มีสิทธิ์เอาไปขาย')
  assert.ok(!out.includes('←'), 'ห้ามเหลือลูกศรในบท')
  assert.ok(!out.includes('เฉลย') && !out.includes('ข้อคิด'), 'ห้ามเหลือป้ายอธิบายในบท')
  assert.match(out, /^ผีตัวนั้นไม่ได้มาเอาชีวิตเขา$/m, 'เนื้อบทบรรทัดเดียวกันต้องอยู่ครบ')
  assert.match(out, /ลูกไม่มีสิทธิ์เอาไปขาย/)
})


const ALL_SUBJECTS = [...new Set(Object.values(TOPIC_SEEDS).flatMap((s) => s.subjects))]
const ALL_CORES = [...new Set(Object.values(TOPIC_SEEDS).flatMap((s) => s.cores))]

/** คำสั่งตัวหลัก + ปมเรื่องของแต่ละข้อ (ข้อตามลำดับเดียวกับหมวด) */
function themeRule(themes) {
  if (!themes?.length) return ''
  return `**ตัวหลักและปมเรื่องของแต่ละข้อ (ระบบกำหนด ห้ามเปลี่ยน):**
${themes.map((t, i) => `${i + 1}. ${t.genre ? `${t.genre} · ` : ''}ตัวหลัก: ${t.subject} · ปมเรื่อง: ${t.core}${t.angle ? ` · มุม: ${GHOST_ANGLE_LABELS[t.angle]}` : ''}`).join('\n')}
- ตัวหลัก = ชนิดผีหรือตัวละครหลักของเรื่อง · ปมเรื่อง = สิ่งที่ตัวละครทำผิดหรือต้นเหตุของเรื่อง — แต่งเรื่องใหม่ให้สองอย่างนี้มาเจอกัน แล้วผลกรรม หักมุม หรือมุกปิดเกิดจากปมนี้เอง
- ชื่อเรื่องควรมีตัวหลักหรือสถานที่ของเรื่อง · ไม่ต้องใส่ปมเรื่องลงในชื่อตรงๆ`
}

/** ข้อความที่พูดถึงรายการไหน — เทียบคำยาวก่อน ("ผีบ้านร้าง" ก่อน "ผี…" ที่สั้นกว่า) */
const findIn = (list, text) => {
  const t = String(text ?? '')
  return [...list].sort((a, b) => b.length - a.length).find((x) => t.includes(x)) ?? null
}

/** ตัวหลักของชื่อเรื่อง (ชนิดผีหรือตัวละครในรายการ) — ไม่ตรงตัวไหน = null */
export const subjectOf = (title) => findIn(ALL_SUBJECTS, title)

/** คอลัมน์ Theme ("ตัวหลัก / ปมเรื่อง") → { subject, core } ตามชื่อในรายการ */
export function parseTheme(text) {
  return { subject: findIn(ALL_SUBJECTS, text), core: findIn(ALL_CORES, text) }
}

/** หยิบ 1 อย่างจาก all — ไม่ซ้ำกับที่ใช้ไปแล้วในชุด และเลี่ยงของคลิปล่าสุด (เหลือไม่พอ → ใช้ของที่ใช้นานที่สุดก่อน) */
function takeOne(all, used, recent) {
  const fresh = shuffle(all.filter((x) => !used.has(x) && !recent.includes(x)))
  const stale = [...recent].reverse().filter((x) => all.includes(x) && !used.has(x))
  const pick = fresh[0] ?? stale[0] ?? shuffle(all)[0]
  used.add(pick)
  return pick
}

/**
 * สุ่มตัวหลัก + ปมเรื่องให้หัวข้อละคู่ ตามหมวดของข้อนั้น — genres = ชื่อหมวดตามลำดับข้อ (จาก pickGenres) หรือจำนวนข้อ (คละหมวด)
 * recent = [{ subject, core }] ของคลิปล่าสุด (ใหม่สุดก่อน) · หัวข้อผีในชุดเดียวกันได้มุมต่างกัน (folk/karma/modern)
 */
export function pickThemes(genres = 5, recent = []) {
  const list = typeof genres === 'number' ? pickGenres('mix', genres) : genres
  const recentSubjects = recent.map((r) => r?.subject).filter(Boolean)
  const recentCores = recent.map((r) => r?.core).filter(Boolean)
  const usedSubjects = new Set()
  const usedCores = new Set()
  let ghostTurn = Math.floor(Math.random() * GHOST_ANGLES.length)
  return list.map((genre) => {
    const c = categoryOf(genre) ?? CATEGORIES[0]
    const seeds = TOPIC_SEEDS[c.id]
    return {
      genre: c.name,
      subject: takeOne(seeds.subjects, usedSubjects, recentSubjects),
      core: takeOne(seeds.cores, usedCores, recentCores),
      ...(c.id === 'ghost' && { angle: GHOST_ANGLES[ghostTurn++ % GHOST_ANGLES.length] }),
    }
  })
}


/** หมวดจากชื่อหมวด/รหัส ('ghost' | 'หมวด 1 · ผีไทย' | 'ผีไทย') — ไม่รู้จัก = null */
export function categoryOf(value) {
  const v = String(value ?? '').trim()
  if (!v || v === 'mix') return null
  if (RETIRED_GENRES[v]) return CATEGORIES.find((c) => c.id === RETIRED_GENRES[v]) ?? null
  return CATEGORIES.find((c) => c.id === v || c.name === v || v.includes(c.name.replace(/^หมวด \d · /, '')) || c.name.includes(v)) ?? null
}

/** หมวดของแต่ละหัวข้อ: ระบุหมวดเดียว → ทุกหัวข้อหมวดนั้น · 'mix'/ว่าง → คละครบทั้ง 5 หมวด */
export function pickGenres(genre = 'mix', count = 5) {
  const one = categoryOf(genre)
  if (one) return Array(count).fill(one.name)
  const picks = shuffle(GENRES)
  while (picks.length < count) picks.push(...shuffle(GENRES))
  return picks.slice(0, count)
}

/** genres = ชื่อหมวดของแต่ละข้อตามลำดับ (จาก pickGenres) */
function genreRule(genres) {
  const used = [...new Set(genres)].map(categoryOf)
  const detail = used.map((c) => `- ${c.name}: ${c.topics}`).join('\n')
  const one = used.length === 1 && genres.length > 1
  const head = one
    ? `**หมวดของคลิปชุดนี้: ${genres[0]}** — ทั้ง ${genres.length} หัวข้อต้องอยู่ในหมวดนี้ แต่ใช้ตัวหลัก พล็อต และมุมเล่าต่างกันทุกข้อ`
    : `**หัวข้อต้องคละหมวด** ใช้หมวดตามลำดับนี้ ข้อละหมวด:\n${genres.map((g, i) => `${i + 1}. ${g}`).join('\n')}`
  return `${head}
${detail}
คอลัมน์ Genre ใส่ชื่อหมวดตามข้างบนเป๊ะๆ
ใช้มุมเล่าต่างกันให้มากที่สุด ห้ามขึ้นต้นด้วย "ทำไม"/"Why" เกิน 1 ข้อ ชื่อเรื่องชวนขนลุกหรือชวนสงสัยแต่ไม่ clickbait เกินเนื้อหา และทำตามกฎ 9 (เรื่องแต่ง ลิขสิทธิ์ และความรุนแรง)`
}

/**
 * กฎเฉพาะหมวดของคลิปนี้ — ต่อท้าย prompt บทและ prompt ภาพ
 * profile = { category: 'ghost'|'saiyasat'|'folk'|'drama'|'comedy', scare, artStyle }
 * หมวดผี/ไสย ได้กฎระดับความสยองของคลิปติดไปด้วย (ทั้งบทและภาพ)
 */
export function categoryRule(profile, stage = 'script') {
  const c = CATEGORIES.find((x) => x.id === profile?.category)
  if (!c) return ''
  const lines = [`**หมวดของคลิปนี้: ${c.name}** — ทำตาม "กฎหมวด ${c.name.match(/\d/)[0]}" ในหัวข้อหมวดคลิปของ Blueprint`]
  if (c.id === 'comedy' && stage !== 'image') lines.push('หมวดนี้ปิดเรื่องด้วยมุกปิด 1 ประโยค (คำพูดหรือภาพที่หักมุมให้ขำ) แทนประโยคสอนใจ · ตลกสะอาด ไม่ล้อปมด้อยร่างกาย ไม่ทะลึ่ง')
  if (c.id === 'folk' && stage === 'image') {
    lines.push('ตัวละครนิทานออกแบบใหม่ในลายเส้นเล่มละบาท — ห้ามวาดให้เหมือนนักแสดงหรือตัวละครจากละครจักรๆ วงศ์ๆ ทางทีวี การ์ตูน หรือภาพยนตร์ที่ยังมีลิขสิทธิ์ · ฉากสู้ไม่มีเลือด')
  }
  const scare = scareRule(profile.scare, c.id, stage)
  if (scare) lines.push(scare)
  // ผีหน้าเดิมทุกคลิปทำให้คนดูเบื่อ — ขั้นภาพของหมวดผี/ไสยต้องออกแบบผีตามชนิดของมัน (ผู้ใช้สั่ง 23 พ.ย. 2026)
  if (stage === 'image' && SCARY.has(c.id)) lines.push(GHOST_LOOK_RULE)
  // ขั้นภาพ: ลายเส้นของคลิป (lemlabaht เสมอ) + ชุดสีของหมวด
  if (stage === 'image') lines.push(artStyleOf(profile).rule, categoryColorRule(c.id))
  return lines.join('\n')
}


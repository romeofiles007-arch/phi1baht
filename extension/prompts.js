// ป้ายหัวบทที่ ChatGPT ชอบแถมบนสุด แม้สั่งห้ามแล้ว: "บทพากย์ 1 นาที — ชื่อเรื่อง", "สคริปต์:", "Narration:"
// หัวข้อ markdown ที่แสดงบนจอไม่มี # แล้ว (แผงอ่านข้อความที่แสดง) จึงหลุดตัวกรอง "# หัวข้อ" ไปเป็นเสียงพากย์/ซับ
// ต้องตามด้วย ":" ขีด วงเล็บ ตัวเลข หรือ "ภาษา…" — "สคริปต์ชีวิตของเรา…" / "บทพากย์นี้…" เป็นเนื้อเรื่อง ไม่ตัด
const HEAD_LABEL = /^(บทพากย์|บทบรรยาย|บทพูด|สคริปต์|เสียงบรรยาย|ชื่อเรื่อง|narration|script|voice-?over)(?=$|\s*[:：\-–—(（\d]|\s+\d|ภาษา)/i
// บรรทัดบอกความยาว: "ความยาวประมาณ 1 นาที", "ครบหนึ่งนาที", "ประมาณ 1.5 นาที"
const LENGTH_NOTE = /^(ความยาว|ยาว|ครบ|ประมาณ|ราว|พอดี)\S*\s*~?(\d+(\.\d+)?|หนึ่ง|สอง|สาม|สี่|ห้า|หก|เจ็ด|แปด|เก้า|สิบ)\s*(นาที|วินาที)\s*(ครับ|ค่ะ)?$/
// หมายเหตุจาก ChatGPT ถึงคนสั่ง (เจอบ่อยหลังสั่งปรับความยาว): "ตัดให้กระชับ ครบหนึ่งนาที", "หากต้องการให้ปรับ…", "Word count: 150"
// ขึ้นต้นด้วยกริยาของคนแก้บท ไม่ใช่ภาษาเล่าเรื่อง — "ตัดความโกรธทิ้งไป" ไม่โดน เพราะต้องเป็น "ตัดให้…"
const EDIT_NOTE = /^(ตัดให้|ปรับให้|ปรับความยาว|เรียบเรียงใหม่|เขียนใหม่ให้|ฉบับ(ปรับ|ใหม่|แก้|ตัด)|ยาวประมาณ|จำนวน(คำ|ตัวอักษร)|รวม(ประมาณ)?\s*~?\d[\d,]*\s*(ตัวอักษร|คำ)|หากต้องการ|ถ้าต้องการ|ต้องการให้(ปรับ|เพิ่ม|ตัด|แก้)|อยากให้(ปรับ|เพิ่ม|ตัด|แก้)|word count|let me know|if you('d)? like|want me to)/i
const isNote = (t) => t.length <= 80 && (LENGTH_NOTE.test(t) || EDIT_NOTE.test(t))

/** ตัดคำนำ/คำปิดท้าย/markdown ที่โมเดลชอบแถมมา ให้เหลือ narration ล้วนตาม OUTPUT 2 */
/**
 * ชวนคุยท้ายคลิป — ผู้ใช้ (8 พ.ย. 2026): "มีแต่คนดู ไม่มีใครตอบอะไรเลย" · ปิดได้ในกล่องตั้งค่าคลิป (script.engage = false)
 * คำถามต้องเกี่ยวกับเรื่องของคลิปนี้ ถามความเห็นหรือประสบการณ์ ให้คนดูอยากพิมพ์ตอบ
 */
export function engageRule(language = 'th') {
  const examples = {
    th: '"ถ้าเป็นคุณ จะทำอย่างไร?" · "ใครเคยเจอเหตุการณ์แบบนี้บ้าง? เล่าให้ฟังในคอมเมนต์หน่อย"',
    en: '"What would you do?" · "Has this ever happened to you? Tell us in the comments."',
  }
  return `- ปิดท้ายบทด้วยประโยคชวนคุย 1–2 บรรทัด ให้คนดูอยากพิมพ์ตอบในคอมเมนต์ — ถามความเห็นหรือประสบการณ์ที่เกี่ยวกับเรื่องนี้ตรงๆ เช่น ${examples[language] ?? examples.th}
  · ใช้ภาษาของ narration · เปลี่ยนคำถามให้เข้ากับเรื่อง ไม่ต้องใช้ตัวอย่างตรงตัว · น้ำเสียงเข้ากับคลิป (สุภาพ ไม่เร่งเร้า)
  · ข้อนี้มีผลเหนือข้อ "ไม่ถามคนดู" หรือ "ห้ามมีคำปิดท้าย" ด้านบน เฉพาะประโยคชวนคุยท้ายบทนี้ · ห้ามขอไลก์/กดติดตาม/แชร์`
}

/** ตัดคำนำ/คำปิดท้าย/markdown ที่โมเดลชอบแถมมา ให้เหลือ narration ล้วนตาม OUTPUT 2 */
export function cleanScript(text) {
  const lines = text
    .replace(/^```[\w]*\n?|```$/gm, '')
    .split('\n')
    .filter((line) => {
      const t = line.trim()
      if (/^#{1,6}\s/.test(t)) return false // หัวข้อ
      if (/^[-*+]\s/.test(t)) return false // bullet
      if (/^\[.*\]$/.test(t)) return false // [visual cue]
      if (/^\(.*\)$/.test(t)) return false // (stage direction)
      return true
    })
    .join('\n')
    .replace(/\*\*|__/g, '')
    // ป้ายอธิบายท้ายบรรทัดในฉากตัวอย่าง ("… ← ① เฉลย") ถ้าโมเดลลอกมาด้วย — ลูกศรไม่มีในบทพากย์จริง
    // ปล่อยไว้จะถูกพากย์และขึ้นซับว่า "ลูกศร หนึ่ง เฉลย" · ทั้งบรรทัดเหลือแต่ป้าย = ทิ้งบรรทัด
    .replace(/[ \t]*←.*$/gm, '')
    .split('\n')
  // ป้ายหัวบท/หมายเหตุ เฉพาะบรรทัดบนสุดก่อนเริ่มเนื้อเรื่อง และบรรทัดท้ายสุดหลังจบเนื้อเรื่อง — กลางเรื่องไม่แตะ
  while (lines.length) {
    const t = lines[0].trim()
    if (t && !((t.length <= 80 && HEAD_LABEL.test(t)) || isNote(t))) break
    lines.shift()
  }
  while (lines.length) {
    const t = lines.at(-1).trim()
    if (t && !isNote(t)) break
    lines.pop()
  }
  return lines.join('\n').replace(/\n{3,}/g, '\n\n').trim()
}

/** ดึงตารางหัวข้อจากคำตอบ STAGE 1 */
export function parseTopics(text) {
  // ChatGPT แสดง markdown table เป็น <table> → innerText ได้คอลัมน์คั่นด้วย tab ไม่ใช่ |
  return [...text.matchAll(/^\|?[ \t]*(\d+)[ \t]*[|\t][ \t]*([^|\t\n]+?)[ \t]*(?:[|\t]|$)/gm)]
    .map((m) => ({ n: Number(m[1]), title: m[2].trim() }))
    .filter((t) => t.title && !/^-+$/.test(t.title) && t.title.toLowerCase() !== 'video title')
}

/** ประมาณความยาวคลิปก่อนยิง TTS จริง — ใช้เช็คว่าสคริปต์ยาวพอสำหรับ n นาทีไหม */
export function estimateMinutes(script, wordsPerMinute = 150, pace = 'normal') {
  // pace 'calm' อ่านช้า + เว้นจังหวะนาน → ตัวอักษรเท่ากันใช้เวลานานกว่า
  // ไทยไม่เว้นวรรคระหว่างคำ → นับตัวอักษรไทยแล้วหารด้วยความยาวคำเฉลี่ย
  // 5.4 ตัว/คำ ที่ 150 คำ/นาที = ~13.5 ตัว/วินาที — วัดจากเสียงพากย์จริง 8 คลิป (12.5–14.3 ตัว/วิ, ต.ค. 2026)
  // เดิมใช้ 4.5 ทำให้ประเมินยาวเกินจริง ~20% → บทที่ยาวพอดีถูกตีว่า "ยาวผิดเป้า" แล้วสั่งเขียนใหม่วนหลายรอบ
  const thaiChars = (script.match(/[฀-๿]/g) || []).length
  const otherWords = (script.replace(/[฀-๿]/g, ' ').match(/[\p{L}\p{N}]+/gu) || []).length
  return (thaiChars / THAI_CHARS_PER_WORD + otherWords) / (wordsPerMinute * paceFactor(pace))
}

/** `my topic!` → `my_topic` ใช้เป็นชื่อโฟลเดอร์และชื่อไฟล์ script */
export function slugify(title) {
  return String(title)
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 60)
}

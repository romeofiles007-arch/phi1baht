/** หัวตาราง → ตำแหน่งคอลัมน์ { title, genre, theme, hook, search, visual, score, why } (ไม่มีคอลัมน์ไหน = ไม่มี key) */
function headerColumns(cells) {
  const tests = [
    ['hook', /hook|ดึงดูด/i],
    ['search', /search|ค้นหา|คนสนใจ/i],
    ['visual', /visual|เล่าด้วยภาพ/i],
    ['why', /why|เหตุผล|reason/i],
    ['theme', /theme|ธีม|ด้านชีวิต|หลักธรรม|หลักคิด/i],
    ['genre', /genre|แนว|หมวด/i],
    ['score', /score|คะแนน|viral/i],
    ['title', /title|ชื่อ|หัวข้อ/i],
  ]
  const map = {}
  cells.forEach((cell, i) => {
    const hit = tests.find(([key, re]) => map[key] == null && re.test(cell))
    if (hit) map[hit[0]] = i
  })
  return map
}

/** ตารางหัวข้อที่มีคะแนน → [{ n, title, genre, hook, search, visual, score, why }] เรียงคะแนนมากไปน้อย */
export function parseScoredTopics(text) {
  const rows = []
  const num = (v) => {
    const n = Number(String(v ?? '').match(/\d+(?:\.\d+)?/)?.[0])
    return Number.isFinite(n) ? n : null
  }
  // คอลัมน์ตามหัวตาราง — ChatGPT บางรอบตัดตารางเหลือ "# | Video Title | Genre | คะแนน Viral" (พ.ย. 2026)
  // ถ้าอ่านตามตำแหน่งอย่างเดียว แถวสั้นกว่า 6 ช่องถูกทิ้งหมด → แผนกคิดหัวข้อล้ม 3 รอบติด
  let header = null
  for (const line of String(text).split(/\r?\n/)) {
    // ChatGPT แสดงตารางเป็น <table> → innerText คั่นด้วย tab · ข้อความดิบคั่นด้วย |
    const cells = line.includes('|') ? line.split('|').map((c) => c.trim()).filter((c, i, a) => !(c === '' && (i === 0 || i === a.length - 1))) : line.split('\t').map((c) => c.trim())
    if (!/^\d+$/.test(cells[0] ?? '')) {
      if (cells.length >= 3 && cells.some((c) => /title|ชื่อ|หัวข้อ/i.test(c))) header = headerColumns(cells)
      continue
    }
    if (header && header.title != null && cells.length < 6) {
      const at = (key) => (header[key] != null ? cells[header[key]] ?? '' : '')
      const title = at('title').replace(/^\*\*|\*\*$/g, '').trim()
      if (!title) continue
      const h = num(at('hook'))
      const s = num(at('search'))
      const v = num(at('visual'))
      let total = num(at('score'))
      if (total != null && total <= 10 && /\/\s*10\b/.test(at('score'))) total *= 10
      if (total == null && h != null && s != null && v != null) total = Math.round(((h + s + v) / 30) * 100)
      // ไม่มีคอลัมน์ Theme → ดูหลักธรรมจากชื่อเรื่อง (ด้านชีวิตเดาจากชื่อไม่แม่น เว้นไว้)
      const themeText = at('theme')
      const theme = themeText ? parseTheme(themeText) : { area: null, dhamma: parseTheme(title).dhamma ?? null }
      rows.push({ n: Number(cells[0]), title, genre: at('genre'), ...(theme.area || theme.dhamma ? { theme } : {}), hook: h, search: s, visual: v, score: total ?? 0, why: at('why') })
      continue
    }
    if (cells.length < 6) continue
    // คอลัมน์ Genre อยู่หลังชื่อ — คำตอบรุ่นเก่าไม่มี (คอลัมน์ที่ 3 เป็นตัวเลข)
    // ห้ามใช้ num() ตัดสิน — ชื่อหมวด "หมวด 1 · ..." มีตัวเลข เคยถูกนับเป็นคะแนน Hook ทั้งคอลัมน์เลื่อน (หมวดหาย คะแนนผิด)
    const isNumber = (v) => /^\s*\d+(?:\.\d+)?\s*(?:\/\s*\d+)?\s*$/.test(v ?? '')
    const genre = cells.length >= 7 && !isNumber(cells[2]) ? cells.splice(2, 1)[0] : ''
    // คอลัมน์ Theme (ด้านชีวิต / หลักธรรม) อยู่หลัง Genre — คำตอบรุ่นก่อนไม่มี
    const themeText = genre && cells.length >= 7 && !isNumber(cells[2]) ? cells.splice(2, 1)[0] : ''
    const [n, title, hook, search, visual, score, ...why] = cells
    if (!title || /^video title$/i.test(title)) continue
    const h = num(hook)
    const s = num(search)
    const v = num(visual)
    let total = num(score)
    if (total == null && h != null && s != null && v != null) total = Math.round(((h + s + v) / 30) * 100)
    const theme = themeText ? parseTheme(themeText) : null
    rows.push({ n: Number(n), title: title.replace(/^\*\*|\*\*$/g, '').trim(), genre, ...(theme ? { theme } : {}), hook: h, search: s, visual: v, score: total ?? 0, why: why.join(' ').trim() })
  }
  return rows.sort((a, b) => b.score - a.score)
}

/**
 * ความยาวบทที่บอก ChatGPT — ภาษาไทยบอกเป็น "ตัวอักษร" ไม่ใช่ "คำ"
 * ไทยไม่เว้นวรรคระหว่างคำ ChatGPT นับคำไทยไม่ได้ (สั่ง 150 คำได้บท 1.4 นาที) แต่นับตัวอักษรได้ใกล้กว่ามาก
 * ตัวเลขเดียวกับ estimateMinutes: 5.4 ตัว/คำ × คำ/นาที (~13.5 ตัว/วินาที ตามเสียงพากย์จริง)
 */
export const THAI_CHARS_PER_WORD = 5.4
/**
 * อักษรจีน 1.7 ตัว = 1 "คำ" ของสูตรเดียวกัน — วัดจาก Edge zh-CN-YunyangNeural เสียงเรียบ (ช้าลง 15% ทุ้มลง เว้นจังหวะแบบหมวด 1)
 * ได้ 2.46 ตัว/วิ รวมช่วงเว้น (ต.ค. 2026) ≈ 1.7 × 2.5 คำ/วิ × 0.57 (ตัวคูณ calm)
 */
export const HAN_CHARS_PER_WORD = 1.7
const HAN = /[\u3400-\u9fff\uf900-\ufaff]/g

/**
 * จังหวะการพูดของคลิป
 *   normal — เล่าเรื่องปกติ ~13.5 ตัวอักษรไทย/วินาที (วัดจากเสียงพากย์จริง)
 *   calm   — หมวด 1 สอนธรรมแบบช้า สงบ เว้นจังหวะ ~8.5 ตัว/วินาที (วัดจากคลิปตัวอย่างที่ผู้ใช้ให้มา ต.ค. 2026: 6.9–8.2 ตัว/วิ รวมช่วงหยุด)
 *            เสียงช้าลง (speed) + เว้นระหว่างบรรทัดนานขึ้น — 2_tts.mjs ใช้ค่าเหล่านี้กับคลิปหมวด 1 เอง
 */
export const PACE = {
  normal: { charsPerSec: 13.5 },
  calm: {
    // 7.7 ตัว/วิ รวมช่วงเว้น — วัดจากบทหมวด 1 จริง 388 ตัวอักษร = 50.4 วิ (ElevenLabs v4 Turbo + tag)
    charsPerSec: 7.7, speed: 0.85, segmentGapMs: 500, paragraphGapMs: 900,
    // ElevenLabs: เสียงเรียบ ทุ้ม สงบแบบพระ — v4 Turbo + tag กำกับน้ำเสียง (v4 ธรรมดาไม่สนใจ stability)
    // วัดจริง ต.ค. 2026: ความต่างของระดับเสียงลดจาก 4.8 → 3.3 semitone · เสียงทุ้มลง 115 → 96 Hz · ~8.3 ตัวอักษร/วิ ขณะพูด
    eleven: { model: 'eleven_v4_turbo', tag: '[calm, steady storyteller voice]', settings: { stability: 0.9, style: 0 } },
    // engine อื่น — ทำให้เรียบ สงบ ทุ้มเท่าที่แต่ละตัวปรับได้
    gemini: { emotion: 'sage' }, // คำสั่งน้ำเสียงแบบนักเล่าเรื่องจีน (EMOTION_STYLE.sage ใน cloud_tts.mjs)
    edge: { pitch: '-20Hz' }, // ช้าตาม speed + ทุ้มลง (วัดจริง: -6Hz ไม่ต่าง · -20Hz ทุ้มลงและเรียบขึ้น เพราะพูดช้าแล้วเสียงสูงขึ้นเอง)
    local: { emotion: 'calm' }, // เสียงของเรา / VoxCPM: ใช้คลิปต้นแบบอารมณ์สงบ + speed
    chatterbox: { exaggeration: 0.3, cfgWeight: 0.3 }, // ลดการใส่อารมณ์ (เรียบ) + พูดช้าลง
  },
}
// ทุกหมวดใช้เสียงเรียบ ช้า แบบหมวด 1 (ผู้ใช้ขอ ต.ค. 2026 ให้โทนเสียงเหมือนกันทั้งช่อง)
export const paceOf = () => 'calm'
const paceFactor = (pace) => (PACE[pace] ?? PACE.normal).charsPerSec / PACE.normal.charsPerSec

export function lengthTarget(language, targetMinutes, wordsPerMinute = 150, pace = 'normal') {
  const words = Math.round(targetMinutes * wordsPerMinute * paceFactor(pace))
  if (language === 'zh') {
    const han = Math.round(words * HAN_CHARS_PER_WORD)
    return `ความยาวเป้าหมาย ${targetMinutes} นาที ≈ ${han} 字 (นับเฉพาะอักษรจีน ไม่นับเครื่องหมาย) · ห้ามเกิน ${Math.round(han * 1.15)} 字
ประมาณ ${Math.max(6, Math.round(han / 10))} บรรทัด บรรทัดละ ~8–12 字 — เสียงพากย์อ่านช้าและเว้นจังหวะ ~2.5 字 ต่อวินาที เขียนเกินคลิปจะยาวเกินเวลา`
  }
  if (language !== 'th') return `ความยาวเป้าหมาย ${targetMinutes} นาที ≈ ${words} words (ไม่เกิน ${Math.round(words * 1.15)} words)`
  const chars = Math.round(words * THAI_CHARS_PER_WORD)
  const perLine = pace === 'calm' ? 22 : 28
  return `ความยาวเป้าหมาย ${targetMinutes} นาที ≈ ${chars} ตัวอักษรไทย (นับเฉพาะตัวอักษร ไม่นับเว้นวรรคและ ...) · ห้ามเกิน ${Math.round(chars * 1.15)} ตัวอักษร
ประมาณ ${Math.max(6, Math.round(chars / perLine))} บรรทัด บรรทัดละ ~${perLine} ตัวอักษร — เสียงพากย์อ่าน${pace === 'calm' ? 'ช้าและเว้นจังหวะ ~8 ตัวอักษรต่อวินาที' : 'ได้ ~13 ตัวอักษรต่อวินาที'} เขียนเกินคลิปจะยาวเกินเวลา`
}

/** บทยาว/สั้นผิดเป้า → สั่งปรับต่อในแชตเดิม (สั้น เร็ว ไม่ต้องส่ง Blueprint ทั้งก้อนซ้ำ) */
export function reviseLengthPrompt(language, { minutes, target, wordsPerMinute = 150, chars, pace = 'normal' }) {
  const shorter = minutes > target
  const words = target * wordsPerMinute * paceFactor(pace)
  const goal = language === 'th' ? `${Math.round(words * THAI_CHARS_PER_WORD)} ตัวอักษรไทย` : language === 'zh' ? `${Math.round(words * HAN_CHARS_PER_WORD)} 字` : `${Math.round(words)} words`
  const now = language !== 'en' && chars ? ` (${chars} ตัวอักษร)` : ''
  return `บทนี้ยาวประมาณ ${minutes.toFixed(1)} นาที${now} แต่เป้าคือ ${target} นาที — ${shorter ? 'ตัดให้สั้นลง' : 'เพิ่มเนื้อหาให้ยาวขึ้น'} เหลือประมาณ ${goal}
${shorter ? 'เก็บประโยคเปิด ปมของเรื่อง ฉากเด็ด จุดพลิก และประโยคปิดไว้ ตัดบรรทัดบรรยากาศ ส่วนที่ซ้ำ หรือส่วนที่ไม่ดันเรื่องไปข้างหน้าออก' : 'เพิ่มอุปสรรคอีกขั้น ฉากเด็ดหรือรายละเอียดจริงของเรื่อง และบทสนทนาสั้นๆ ของตัวละคร — ห้ามยืดด้วยบรรยากาศ คำสอน หรือการโยงชีวิตคนยุคนี้ ห้ามแต่งข้อเท็จจริงหรือคำพูดของบุคคลจริงเพิ่ม'}
ตอบเป็น narration ฉบับใหม่ทั้งหมดอย่างเดียว รูปแบบเดิม (1 บรรทัด = 1 ช่วงลมหายใจ) ไม่มีคำนำหรือคำปิดท้าย
ห้ามใส่หัวข้อ (เช่น "บทพากย์ ${target} นาที — …") และห้ามบอกว่าแก้อะไรไป (เช่น "ตัดให้กระชับแล้ว", "ครบ ${target} นาที") — ทุกบรรทัดที่ตอบจะถูกอ่านออกเสียงในคลิป`
}


// ทุกหมวดใช้เสียงเรียบ ช้า โทนเดียวกันทั้งช่อง
export const paceOf = () => 'calm'
const paceFactor = (pace) => (PACE[pace] ?? PACE.normal).charsPerSec / PACE.normal.charsPerSec

export function lengthTarget(language, targetMinutes, wordsPerMinute = 150, pace = 'normal') {
  const words = Math.round(targetMinutes * wordsPerMinute * paceFactor(pace))
  if (language !== 'th') return `ความยาวเป้าหมาย ${targetMinutes} นาที ≈ ${words} words (ไม่เกิน ${Math.round(words * 1.15)} words)`
  const chars = Math.round(words * THAI_CHARS_PER_WORD)
  const perLine = pace === 'calm' ? 22 : 28
  return `ความยาวเป้าหมาย ${targetMinutes} นาที ≈ ${chars} ตัวอักษรไทย (นับเฉพาะตัวอักษร ไม่นับเว้นวรรคและ ...) · ห้ามเกิน ${Math.round(chars * 1.15)} ตัวอักษร
ประมาณ ${Math.max(6, Math.round(chars / perLine))} บรรทัด บรรทัดละ ~${perLine} ตัวอักษร — เสียงพากย์อ่าน${pace === 'calm' ? 'ช้าและเว้นจังหวะ ~8 ตัวอักษรต่อวินาที' : 'ได้ ~13 ตัวอักษรต่อวินาที'} เขียนเกินคลิปจะยาวเกินเวลา`
}

/** บทยาว/สั้นผิดเป้า → สั่งปรับต่อในแชตเดิม (สั้น เร็ว ไม่ต้องส่ง Blueprint ทั้งก้อนซ้ำ) */

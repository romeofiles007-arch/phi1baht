export function endsCliffhanger(script) {
  const lines = String(script ?? '').split(/\r?\n/).map((l) => l.trim()).filter(Boolean)
  return lines.slice(-3).some((l) => CLIFFHANGER.test(l))
}

/**
 * บทที่เฉลยไม่เป็นคำพูด — ช่วงท้ายไม่มีบรรทัดไหนบอกตรงๆ ว่าใครคือต้นเหตุ มาทำไม หรือเบาะแสหมายถึงอะไร
 * ผู้ใช้ (23 พ.ย. 2026): "เนื้อเรื่องออกมาไม่เข้าใจ คือตัดจบแบบงงๆ" — คลิปผีกองกอยเฉลยด้วยภาพกับคำสั่งของผี
 * ("ดูใต้ขอนไม้!") ไม่มีบรรทัดอธิบายเลย ดูจบแล้วไม่รู้ว่าผีคือใคร มาทำไม · autopilot ใช้สั่งเขียนใหม่
 * เป็นการเดาจากคำ: บทที่เฉลยอยู่แล้วแต่ไม่ใช้คำพวกนี้ก็อาจโดนด้วย — เอียงไปทางขอให้เฉลยชัดขึ้น
 * ดีกว่าปล่อยบทที่ดูจบแล้วงงออกเป็นคลิป (รอบสุดท้ายยอมรับ ไม่ให้งานผลิตค้าง)
 */
const REVEAL_WORD = /ที่จริง|ความจริง|แท้จริง|จริงๆ|เพราะ|ก็คือ|นั่นคือ|นั่นเอง|กลายเป็นว่า|รู้ว่า|เป็นของ|(?:ไม่ใช่|ไม่ได้)[^\n]{0,40}(?:แต่|หรอก)|actually|the truth|turns out|because|it was (?:never|always)/i
export function lacksReveal(script) {
  const lines = String(script ?? '').split(/\r?\n/).map((l) => l.trim()).filter(Boolean)
  if (lines.length < 6) return false // บทสั้นมาก (เศษบท/ทดสอบ) ไม่ตัดสิน
  const tail = lines.slice(-Math.max(4, Math.ceil(lines.length * 0.4)))
  return !tail.some((l) => REVEAL_WORD.test(l))
}

/** theme = { subject, core } ที่ระบบกำหนดตอนคิดหัวข้อ — ให้บทยึดตัวหลักและปมเรื่องนี้ ไม่ไหลไปเป็นผีตัวเดิมทุกคลิป */
function scriptThemeRule(theme) {
  if (!theme?.subject && !theme?.core) return ''
  return `\n${theme.subject ? `ตัวหลักของคลิปนี้: ${theme.subject}` : ''}${theme.subject && theme.core ? ' · ' : ''}${theme.core ? `ปมเรื่องของคลิปนี้: ${theme.core}` : ''}
- ใช้ตัวหลักและปมเรื่องนี้เป็นแกนของเรื่อง — ปมเรื่องเป็นต้นเหตุ แล้วผลกรรม หักมุม หรือมุกปิดเกิดจากปมนี้เอง · ห้ามเปลี่ยนเป็นผีหรือตัวละครหลักตัวอื่น\n`
}

/**
 * สินค้าที่ขอให้โผล่ในเรื่อง (ตัวทดลอง) — ผู้ใช้วางลิ้ง Shopee ในแผงข้าง
 * ชื่อสินค้าอ่านจากตัวลิ้งเอง ไม่ยิงเน็ตไปหา Shopee (Shopee บล็อกการดึงข้อมูล และเปลี่ยนหน้าเว็บบ่อย)
 * รูปแบบลิ้งที่มีชื่ออยู่ใน URL: shopee.co.th/<ชื่อสินค้า>-i.<shopId>.<itemId>
 * ลิ้งย่อ (th.shp.ee/xxxx) และ shopee.co.th/product/<shopId>/<itemId> ไม่มีชื่อ → คืน name: null ให้ผู้ใช้พิมพ์เอง
 */
const PROMO_WORD = /^(ส่งฟรี|พร้อมส่ง|ของแท้|ราคาถูก|ถูกที่สุด|ลดราคา|โปรโมชั่น|โปรโมชัน|แถม|ฟรี|ใหม่|hot|sale|free|new|cod|ส่งไว|เก็บเงินปลายทาง|รับประกัน|มีประกัน|ขายดี|แท้|ด่วน|\d+(บาท|ฺbath|baht)?|[฿$]\d+|\d+%)$/i
/**
 * วลีโฆษณาที่ร้านยัดไว้หน้าชื่อสินค้าจริง — ตัดทั้งคำที่มีวลีพวกนี้อยู่ข้างใน
 * เจอจริง 23 พ.ย. 2026: "GFShop-มี2สีให้เลือกกันไปเลย-🎉-พร้อมส่งทุกบ้าน-🚚-รองเท้าผ้าใบ"
 * ชื่อสินค้าจริงอยู่ท้ายสุด ถ้าไม่ตัดของพวกนี้ออก ชื่อที่ได้จะเป็นคำโฆษณาล้วนแล้วชื่อจริงโดนตัดทิ้ง
 */
const PROMO_PHRASE = /ให้เลือก|กันไปเลย|พร้อมส่ง|ส่งทุก|ส่งเร็ว|ราคาส่ง|แถมฟรี|ลดราคา|ลดหนัก|ขายดี|โปรโม|ถูกมาก|คุ้มมาก|จัดส่ง|เก็บปลายทาง|ทักแชท|สินค้าพร้อม/
/** อีโมจิและสัญลักษณ์ตกแต่งที่ร้านใส่คั่น — ไม่ใช่ส่วนหนึ่งของชื่อสินค้า */
const DECOR = /[\p{Extended_Pictographic}☀-➿️‍]/gu
export function productFromUrl(url) {
  const raw = String(url ?? '').trim()
  if (!raw) return null
  let path
  try {
    const u = new URL(raw.startsWith('http') ? raw : `https://${raw}`)
    if (!/(^|\.)shopee\.[a-z.]+$|(^|\.)shp\.ee$/i.test(u.hostname)) return null
    path = u.pathname
  } catch {
    return null
  }
  // ชื่อสินค้าอยู่หน้า "-i.<ตัวเลข>.<ตัวเลข>" — ลิ้งแบบอื่นไม่มีชื่อให้อ่าน · ส่วนนี้เป็น ASCII จึงหาจาก path ดิบได้
  const slug = path.replace(/^\/+/, '').match(/^(.+?)-i\.\d+\.\d+/)?.[1]
  if (!slug) return { url: raw, name: null }
  // decode ทีละคำ: ชื่อสินค้า Shopee มี % อยู่บ่อย ("ลด50%") ซึ่งไม่ใช่ลำดับ escape ที่ถูกต้อง
  // decode ทั้งก้อนจะพังทั้งชื่อ — ทีละคำแล้วคำที่พังยังเป็นคำโฆษณาที่จะถูกตัดทิ้งอยู่ดี
  let words = slug
    .split('-')
    .map((w) => {
      try {
        return decodeURIComponent(w).replace(DECOR, '').trim()
      } catch {
        return ''
      }
    })
    .filter((w) => w && !PROMO_WORD.test(w) && !PROMO_PHRASE.test(w) && !/^[.,|·•]+$/.test(w))
  // ชื่อร้านมักอยู่คำแรกและเป็นอักษรอังกฤษล้วน ("GFShop") — ตัดทิ้งเมื่อยังมีคำไทยเหลืออยู่
  if (words.length > 1 && /^[A-Za-z0-9._]+$/.test(words[0]) && words.slice(1).some((w) => /[฀-๿]/.test(w))) words = words.slice(1)
  const name = words
    .slice(0, 8)
    .join(' ')
    .replace(/\s{2,}/g, ' ')
    .slice(0, 60)
    .trim()
  return { url: raw, name: name || null }
}


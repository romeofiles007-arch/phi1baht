const SCARE_PICKS = ['light', 'medium', 'strong']
/** ค่าที่ตั้ง → ระดับของคลิปนี้ ('light' | 'medium' | 'strong') — 'random' สุ่มตอนเรียก · ไม่รู้จัก = กลาง */
export const resolveScare = (level, rand = Math.random) =>
  level === 'random' ? SCARE_PICKS[Math.min(2, Math.floor(rand() * 3))] : SCARE_PICKS.includes(level) ? level : 'medium'

/** หมวดที่ใช้ระดับความสยอง — 'mix'/ว่าง = ยังไม่รู้หมวด นับว่าใช้ (อาจได้หัวข้อผี) */

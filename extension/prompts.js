/**
 * บทที่เทศนายาวตอนท้าย (≥ 2 ใน 4 บรรทัดท้ายเป็นข้อคิด/บทเรียน) — autopilot ใช้สั่งเขียนใหม่
 * ประโยคปิดสอนใจบรรทัดเดียวแบบเล่มละบาทไม่นับ · คำว่า "สอน" ในเนื้อเรื่อง (ครูสอนคาถา) ไม่นับ
 */
const LECTURE_LINE = /ข้อคิด|บทเรียน|สอนเรา|สอนให้(เรา|รู้|คุณ|เห็น)|สอนคุณ|เรื่องนี้(บอก|สอน)|นำไปใช้|เอาไปใช้|ในชีวิตจริง|ในชีวิตของ(เรา|คุณ)|ชีวิตคนยุคนี้|ยุคนี้เรา|จำไว้ว่า|\blessons?\b|teaches us|the moral|in our (own )?lives/i
export function endsWithLecture(script) {
  const lines = String(script ?? '').split(/\r?\n/).map((l) => l.trim()).filter(Boolean)
  return lines.slice(-4).filter((l) => LECTURE_LINE.test(l)).length >= 2
}

/** บทที่จบค้าง ("ติดตามตอนต่อไป") ใน 3 บรรทัดท้าย — autopilot ใช้สั่งเขียนใหม่ */
const CLIFFHANGER = /ติดตาม(ตอน|ภาค)|ตอนต่อไป|ภาคต่อ|ตอนหน้า|คราวหน้าจะเล่า|to be continued|next episode|part 2/i
export function endsCliffhanger(script) {
  const lines = String(script ?? '').split(/\r?\n/).map((l) => l.trim()).filter(Boolean)
  return lines.slice(-3).some((l) => CLIFFHANGER.test(l))
}

/** theme = { subject, core } ที่ระบบกำหนดตอนคิดหัวข้อ — ให้บทยึดตัวหลักและปมเรื่องนี้ ไม่ไหลไปเป็นผีตัวเดิมทุกคลิป */
function scriptThemeRule(theme) {
  if (!theme?.subject && !theme?.core) return ''
  return `\n${theme.subject ? `ตัวหลักของคลิปนี้: ${theme.subject}` : ''}${theme.subject && theme.core ? ' · ' : ''}${theme.core ? `ปมเรื่องของคลิปนี้: ${theme.core}` : ''}
- ใช้ตัวหลักและปมเรื่องนี้เป็นแกนของเรื่อง — ปมเรื่องเป็นต้นเหตุ แล้วผลกรรม หักมุม หรือมุกปิดเกิดจากปมนี้เอง · ห้ามเปลี่ยนเป็นผีหรือตัวละครหลักตัวอื่น\n`
}

